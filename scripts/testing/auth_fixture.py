"""Headless, isolated loopback-only SSH authentication fixture. Never used by the app.

Requires a test Python with paramiko. All generated keys/secrets remain in the caller's
ignored .tools directory. The public-key fingerprint is computed from generated bytes,
independently of the SSH client's trust callback. No actual Linux server is modified.
"""
import base64
import hashlib
import json
import os
import secrets
import socket
import stat
import sys
import threading
import time

import paramiko

root = os.path.abspath(sys.argv[1])
os.makedirs(root, exist_ok=True)
hostkey = paramiko.RSAKey.generate(2048)
clientkey = paramiko.RSAKey.generate(2048)
clientkey.write_private_key_file(os.path.join(root, "client.key"))
password = "  пароль ' \" Ω " + secrets.token_hex(12) + "  "
otp = secrets.token_hex(5)
statistics = {"active": {}, "passwordReceived": {}}
statistics_gate = threading.Lock()


def record(category, mode, change=1):
    with statistics_gate:
        values = statistics[category]
        values[mode] = values.get(mode, 0) + change
        temporary = os.path.join(root, "statistics.tmp")
        with open(temporary, "w", encoding="utf-8") as output:
            json.dump(statistics, output)
        # Windows file scanners/readers can briefly deny replacement. Statistics must not
        # abort the SSH worker or turn an authentication regression test into a fixture race.
        for attempt in range(200):
            try:
                os.replace(temporary, os.path.join(root, "statistics.json"))
                break
            except PermissionError:
                time.sleep(0.005)
        return values[mode]

for name, value in [("password.txt", password), ("otp.txt", otp)]:
    with open(os.path.join(root, name), "w", encoding="utf-8", newline="") as output:
        output.write(value)


class Files(paramiko.SFTPServerInterface):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.base = os.path.realpath(os.path.join(root, "files"))
        os.makedirs(os.path.join(self.base, "empty-folder"), exist_ok=True)
        readme = os.path.join(self.base, "README.txt")
        if not os.path.exists(readme):
            with open(readme, "wb") as output:
                output.write(b"Isolated authentication fixture file.\n")

    def local(self, path):
        if "\\" in path or "\0" in path:
            raise PermissionError("invalid fixture path")
        if path in (".", "~"):
            path = "/"
        value = os.path.realpath(os.path.join(self.base, path.lstrip("/")))
        if os.path.commonpath([self.base, value]) != self.base:
            raise PermissionError("fixture root containment")
        return value

    def canonicalize(self, path):
        try:
            relative = os.path.relpath(self.local(path), self.base).replace(os.sep, "/")
            return "/" if relative == "." else "/" + relative
        except (OSError, ValueError):
            return "/"

    def stat(self, path):
        try:
            return paramiko.SFTPAttributes.from_stat(os.stat(self.local(path)))
        except OSError as error:
            return paramiko.SFTPServer.convert_errno(error.errno or 13)

    lstat = stat

    def list_folder(self, path):
        try:
            folder = self.local(path)
            return [paramiko.SFTPAttributes.from_stat(os.stat(os.path.join(folder, name)), filename=name)
                    for name in os.listdir(folder)]
        except OSError as error:
            return paramiko.SFTPServer.convert_errno(error.errno or 13)

    def open(self, path, flags, attr):
        if flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT | os.O_TRUNC):
            return paramiko.SFTP_PERMISSION_DENIED
        try:
            handle = paramiko.SFTPHandle(flags)
            handle.readfile = open(self.local(path), "rb")
            return handle
        except OSError as error:
            return paramiko.SFTPServer.convert_errno(error.errno or 13)


class Server(paramiko.ServerInterface):
    def __init__(self, mode):
        self.mode = mode
        self.primary = False

    def get_allowed_auths(self, username):
        if self.mode == "interactive":
            return "keyboard-interactive"
        if self.primary:
            return "keyboard-interactive"
        if self.mode == "key-mfa":
            return "publickey"
        return "password"

    def check_auth_password(self, username, supplied):
        attempt = record("passwordReceived", self.mode)
        if self.mode == "password-delay":
            gate = os.path.join(root, "release-password-" + str(attempt))
            deadline = time.monotonic() + 15
            while not os.path.exists(gate) and time.monotonic() < deadline:
                time.sleep(0.01)
        if self.mode in ("interactive", "key-mfa") or username != "fixture" or supplied != password:
            return paramiko.AUTH_FAILED
        self.primary = True
        return paramiko.AUTH_PARTIALLY_SUCCESSFUL if self.mode == "password-mfa" else paramiko.AUTH_SUCCESSFUL

    def check_auth_publickey(self, username, key):
        if self.mode == "key-mfa" and username == "fixture" and key.asbytes() == clientkey.asbytes():
            self.primary = True
            return paramiko.AUTH_PARTIALLY_SUCCESSFUL
        return paramiko.AUTH_FAILED

    def check_auth_interactive(self, username, submethods):
        if username != "fixture" or (not self.primary and self.mode != "interactive"):
            return paramiko.AUTH_FAILED
        # Include "password" in the OTP prompt: auto-substitution by text is a regression.
        return paramiko.InteractiveQuery("fixture", "authentication test", ("One-time password:", False))

    def check_auth_interactive_response(self, responses):
        return paramiko.AUTH_SUCCESSFUL if responses == [otp] else paramiko.AUTH_FAILED

    def check_channel_request(self, kind, channel_id):
        return paramiko.OPEN_SUCCEEDED if kind == "session" else paramiko.OPEN_FAILED_ADMINISTRATIVELY_PROHIBITED

    def check_channel_exec_request(self, channel, command):
        if self.mode in ("exec-denied", "both-denied"):
            return False
        def respond():
            time.sleep(0.02)
            try:
                channel.sendall(b"SSHExplorer-probe" if command == b"printf 'SSHExplorer-probe'" else b"alive")
                channel.send_exit_status(0)
                channel.close()
            except Exception:
                pass
        threading.Thread(target=respond, daemon=True).start()
        return True

    def check_channel_subsystem_request(self, channel, name):
        if self.mode in ("sftp-denied", "both-denied"):
            return False
        return super().check_channel_subsystem_request(channel, name)

    def check_channel_pty_request(self, channel, term, width, height, pixelwidth, pixelheight, modes):
        return True

    def check_channel_shell_request(self, channel):
        return True


def handle(connection, mode):
    record("active", mode)
    transport = paramiko.Transport(connection)
    try:
        transport.add_server_key(hostkey)
        transport.set_subsystem_handler("sftp", paramiko.SFTPServer, Files)
        transport.start_server(server=Server(mode))
        channels = []
        while transport.is_active():
            channel = transport.accept(0.1)
            if channel is not None:
                channels.append(channel)
    except Exception:
        pass
    finally:
        transport.close()
        record("active", mode, -1)


def listen(listener, mode):
    while True:
        connection, _ = listener.accept()
        threading.Thread(target=handle, args=(connection, mode), daemon=True).start()


ports = {}
for mode in ["password", "password-delay", "password-mfa", "key-mfa", "interactive", "sftp-denied", "exec-denied", "both-denied"]:
    listener = socket.socket()
    listener.bind(("127.0.0.1", 0))
    listener.listen(16)
    ports[mode] = listener.getsockname()[1]
    threading.Thread(target=listen, args=(listener, mode), daemon=True).start()

fingerprint = "SHA256:" + base64.b64encode(hashlib.sha256(hostkey.asbytes()).digest()).decode().rstrip("=")
with open(os.path.join(root, "fixture.json.tmp"), "w", encoding="utf-8") as output:
    json.dump({"Host": "127.0.0.1", "Username": "fixture", "Ports": ports,
               "SecretFile": os.path.join(root, "password.txt"), "OtpFile": os.path.join(root, "otp.txt"),
               "PrivateKeyPath": os.path.join(root, "client.key"), "ExpectedHostFingerprint": fingerprint}, output)
os.replace(os.path.join(root, "fixture.json.tmp"), os.path.join(root, "fixture.json"))
print("READY", flush=True)
threading.Event().wait()
